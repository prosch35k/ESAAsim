#!/usr/bin/env python3
"""Builds data/scenarios.js from every .txt sweatbox file in scenarios/.
The file name (without .txt) is the name shown in the Scenario dialog; files are listed alphabetically.
Also bumps the ?v= cache-buster in index.html. Run from anywhere:  python3 tools/build_scenarios.py
A GitHub Action (.github/workflows/scenarios.yml) runs this automatically when files in scenarios/ are pushed."""
import json, pathlib, re, datetime
root = pathlib.Path(__file__).resolve().parent.parent
out = []
for f in sorted((root / 'scenarios').glob('*.txt'), key=lambda p: p.name.lower()):
    txt = f.read_text(encoding='utf-8', errors='replace').replace('\r\n', '\n')
    out.append(json.dumps(f.stem) + ':' + json.dumps(txt))
(root / 'data' / 'scenarios.js').write_text(
    '/* GENERATED by tools/build_scenarios.py from scenarios/*.txt - do not edit by hand */\n'
    'window.SCENARIOS={\n' + ',\n'.join(out) + '\n};\n', encoding='utf-8')
print('wrote', len(out), 'scenario(s):', ', '.join(f.stem for f in sorted((root / 'scenarios').glob('*.txt'))))
ix = root / 'index.html'
v = datetime.datetime.now(datetime.timezone.utc).strftime('%Y%m%d%H%M')
ix.write_text(re.sub(r'\?v=\d{12}', '?v=' + v, ix.read_text(encoding='utf-8')), encoding='utf-8')
